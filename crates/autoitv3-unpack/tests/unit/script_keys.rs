//! Unit tests for `script::keys`'s keystreams against the reference vectors.
//!
//! Kept out of `keys.rs` so the module reads as implementation;
//! `#[path]` pulls the file back in as a unit-test module, which is what
//! lets it reach private state the module does not expose.

use super::*;

/// The reference implementation's `LAME(0x2477).get_n_next(64)`.
///
/// `0x2477` is `au3_ResContent` for `EA06`, the seed every embedded file's
/// body is decrypted with, so this vector is the one that matters most.
#[test]
fn the_ea06_stream_matches_the_reference_byte_for_byte() {
    let expected: [u8; 64] = [
        0x28, 0xBA, 0xCA, 0x35, 0xB3, 0x8B, 0x3E, 0xB9, 0x51, 0x37, 0x58, 0x9E, 0x3C, 0x62,
        0xC4, 0x0D, 0x78, 0x52, 0xB3, 0x92, 0x3C, 0xC6, 0x50, 0xAD, 0x6B, 0xC0, 0x75, 0xF5,
        0xC0, 0x32, 0x3F, 0x34, 0x72, 0x22, 0xF3, 0xFE, 0xC2, 0x5C, 0x0B, 0x82, 0xA9, 0xFA,
        0x28, 0x81, 0x07, 0xBC, 0x20, 0x7D, 0x9F, 0xAD, 0x9A, 0x7C, 0xE5, 0xEB, 0xFD, 0x95,
        0x38, 0xC4, 0x00, 0xB5, 0xA7, 0x2C, 0x58, 0xF2,
    ];
    assert_eq!(ea06_keystream(0x2477, 64), expected.to_vec());
}

/// `LAME(0xB33F)`: the seed the *name* fields are keyed with.
#[test]
fn the_ea06_name_stream_matches_the_reference() {
    let expected: [u8; 32] = [
        0x82, 0x7B, 0x79, 0xAC, 0x36, 0x14, 0x77, 0x99, 0x1E, 0x76, 0x5D, 0x24, 0xE2, 0x66,
        0xCA, 0x5C, 0x89, 0x17, 0x24, 0x85, 0x71, 0xCA, 0x0F, 0xD5, 0x6A, 0x7D, 0x7E, 0x49,
        0x80, 0x42, 0x92, 0x2F,
    ];
    assert_eq!(ea06_keystream(0xB33F, 32), expected.to_vec());
}

/// The reference's `MT(0x12345678).get_bytes(64)`.
#[test]
fn the_ea05_twister_matches_the_reference() {
    let expected: [u8; 64] = [
        0xA1, 0x7D, 0x52, 0xC0, 0x5D, 0x3E, 0x6D, 0xCC, 0x6E, 0x6B, 0xFC, 0xE5, 0x21, 0xB3,
        0x87, 0xD8, 0xCD, 0xB5, 0x87, 0xAA, 0x8A, 0x1E, 0xD0, 0x59, 0xF9, 0xD5, 0x39, 0x13,
        0xD7, 0x8E, 0x8F, 0x15, 0x13, 0x7D, 0x6F, 0x90, 0x33, 0xF7, 0x00, 0x23, 0xB0, 0xF1,
        0x91, 0x88, 0x68, 0x4D, 0x56, 0xA0, 0x50, 0x3E, 0x6D, 0x81, 0x8A, 0x87, 0xA9, 0xDD,
        0x99, 0xC6, 0x75, 0x63, 0xF4, 0x4C, 0x23, 0xAF,
    ];
    assert_eq!(ea05_keystream(0x12345678, 64), expected.to_vec());
}

/// A block boundary has to be twisted before the word is handed out, which
/// only shows up past 624 bytes — a length the vectors above do not reach.
#[test]
fn the_twister_reloads_a_block_after_624_bytes() {
    let long = ea05_keystream(1, 700);
    assert_eq!(long.len(), 700);
    // The seventh hundred is not a copy of the first: the state was
    // regenerated rather than the stream restarting.
    assert_ne!(&long[..100], &long[624..700]);
    assert_ne!(ea05_keystream(1, 700), ea05_keystream(2, 700));
}

#[test]
fn xor_is_its_own_inverse() {
    let plain = b"the quick brown fox".to_vec();
    let once = xor_keystream(&plain, 0x2477, false);
    assert_eq!(xor_keystream(&once, 0x2477, false), plain);
}
